# 1단계: 유클리드 호제법으로 최대공약수(GCD) 구하기


def gcd(a, b):
    while b != 0:
        a, b = b, a % b
    return a


# def gcd(a, b): → 두 수 a, b를 받아서 최대공약수를 돌려주는 함수를 만들겠다
# while b != 0: → b가 0이 아닌 동안 계속 반복하겠다 (b가 0이 되는 순간 멈춤)
# a, b = b, a % b → 나눈 수 b는 앞(a)으로, 나머지는 뒤(b)로 동시에 보내겠다
# return a → 반복이 끝났을 때 앞자리 a에 남은 값이 최대공약수이므로 돌려주겠다




# 1단계 가시화: gcd의 매 바퀴를 divmod로 풀어서 보여주기


def gcd_trace(a, b):
    print(f"시작: ({a}, {b})")
    count = 1
    while b != 0:
        q, r = divmod(a, b)
        print(f"{count}바퀴: {a} ÷ {b} = 몫 {q}, 나머지 {r} → ({b}, {r})")
        a, b = b, r
        count += 1
    print("b가 0이 됨 → 멈춤")
    return a


# print(f"시작: ({a}, {b})") → 반복 전의 처음 쌍을 찍겠다
# count = 1 → 몇 번째 바퀴인지 세는 숫자를 1부터 시작하겠다
# q, r = divmod(a, b) → 몫은 q에, 나머지는 r에 나눠 담겠다 (언패킹)
# print(f"{count}바퀴: ...") → 이번 바퀴의 나눗셈과 새로 만들어질 쌍을 한 줄로 찍겠다
# a, b = b, r → 나눈 수 b는 앞으로, 나머지 r은 뒤로 보내겠다 (gcd의 a % b와 같은 값)
# count += 1 → 바퀴 번호를 1 늘리겠다
# return a → gcd와 똑같이 최대공약수를 돌려주겠다


